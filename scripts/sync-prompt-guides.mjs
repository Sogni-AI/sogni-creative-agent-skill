// Writes the generated prompt-guide sections of references/video-prompting.md
// and references/image-prompting.md from the pinned
// @sogni-ai/sogni-intelligence-client prompt-guides: the rules Sogni's own
// prompt writers use, which `sogni-agent prompt-guide` prints. Each section sits
// between `<!-- BEGIN GENERATED PROMPT GUIDE: <name> -->` and
// `<!-- END GENERATED PROMPT GUIDE: <name> -->`; everything outside those
// sentinels is hand-written. scripts/check-prompt-guides.mjs fails when a
// section differs from what this script would write.
//
// Every command a section prints is run through the CLI first, so the docs only
// name a -m value that `sogni-agent prompt-guide` resolves to that guide.
import { readFileSync, writeFileSync } from 'node:fs';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  MODEL_PROMPT_GUIDES,
  renderModelPromptGuide,
} from '@sogni-ai/sogni-intelligence-client/prompt-guides';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const require = createRequire(import.meta.url);
const IC_PACKAGE = '@sogni-ai/sogni-intelligence-client';
export const INSTALLED_IC_VERSION = require(`${IC_PACKAGE}/package.json`).version;

export const VIDEO_DOC = 'references/video-prompting.md';
export const IMAGE_DOC = 'references/image-prompting.md';
export const IMAGE_SECTION = 'image-models';

const IMAGE_MODES = new Set(['generate', 'edit']);

// The mode shown in full for each video family: its first registry mode
// (t2v), except WAN 2.2, whose everyday use is the default single-image
// animation model.
const REPRESENTATIVE_MODE = Object.freeze({ 'wan-2.2': 'i2v' });

// -m values tried before a guide's own model ids. `-m wan22` renders t2v and
// i2v on LTX 2.5, so the WAN 2.2 guides are reached through wan22-i2v.
const PREFERRED_MODEL = Object.freeze({ 'wan-2.2': 'wan22-i2v' });

const GENERATED_NOTE = `<!-- Generated by npm run sync:prompt-guides from ${IC_PACKAGE} ${INSTALLED_IC_VERSION}; edit the rules there, not here. -->`;

const isImageFamily = (modes) => Object.keys(modes).every((mode) => IMAGE_MODES.has(mode));

export const VIDEO_FAMILIES = Object.keys(MODEL_PROMPT_GUIDES)
  .filter((family) => !isImageFamily(MODEL_PROMPT_GUIDES[family]));
export const IMAGE_FAMILIES = Object.keys(MODEL_PROMPT_GUIDES)
  .filter((family) => isImageFamily(MODEL_PROMPT_GUIDES[family]));

const sentinel = (kind, name) => `<!-- ${kind} GENERATED PROMPT GUIDE: ${name} -->`;

function runPromptGuide(model, mode) {
  return new Promise((resolve, reject) => {
    const child = spawn(
      process.execPath,
      [join(repoRoot, 'sogni-agent.mjs'), 'prompt-guide', model, '--mode', mode, '--json', '--no-update-check'],
      { cwd: repoRoot, stdio: ['ignore', 'pipe', 'pipe'], env: { ...process.env, OPENCLAW_PLUGIN_CONFIG: '' } }
    );
    let stdout = '';
    child.stdout.on('data', (chunk) => { stdout += chunk; });
    child.on('error', reject);
    child.on('close', () => {
      try {
        resolve(JSON.parse(stdout));
      } catch {
        reject(new Error(`sogni-agent prompt-guide ${model} --mode ${mode} printed no JSON`));
      }
    });
  });
}

async function mapWithConcurrency(items, limit, fn) {
  const results = new Array(items.length);
  let next = 0;
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index]);
    }
  });
  await Promise.all(workers);
  return results;
}

// The first -m value the CLI resolves to exactly this family and mode.
async function commandModelFor(family, mode) {
  const guide = MODEL_PROMPT_GUIDES[family][mode];
  const candidates = [...new Set([PREFERRED_MODEL[family], ...guide.models].filter(Boolean))];
  for (const model of candidates) {
    const result = await runPromptGuide(model, mode);
    if (result.success && result.family === family && result.mode === mode) return model;
  }
  throw new Error(
    `No -m value resolves to the ${family} ${mode} prompt guide through sogni-agent prompt-guide `
    + `(tried ${candidates.join(', ')}). Add one to PREFERRED_MODEL in scripts/sync-prompt-guides.mjs.`
  );
}

async function commandModels() {
  const pairs = Object.entries(MODEL_PROMPT_GUIDES)
    .flatMap(([family, modes]) => Object.keys(modes).map((mode) => [family, mode]));
  const models = await mapWithConcurrency(pairs, 8, ([family, mode]) => commandModelFor(family, mode));
  const byKey = new Map();
  pairs.forEach(([family, mode], index) => byKey.set(`${family}/${mode}`, models[index]));
  return byKey;
}

const command = (model, mode) => `sogni-agent prompt-guide ${model} --mode ${mode}`;

function videoSection(family, models) {
  const modes = MODEL_PROMPT_GUIDES[family];
  const mode = REPRESENTATIVE_MODE[family] ?? Object.keys(modes)[0];
  const guide = modes[mode];
  const model = models.get(`${family}/${mode}`);
  const lines = [
    GENERATED_NOTE,
    '',
    `### Sogni's prompt rules: ${family}`,
    '',
    `\`${command(model, mode)}\` prints the rules Sogni's own prompt writer uses for ${guide.title}, shown in full below. `
      + 'Print the guide for the mode you will run before writing its prompt:',
    '',
    '| Mode | Guide | Command |',
    '| --- | --- | --- |',
  ];
  for (const [entryMode, entry] of Object.entries(modes)) {
    lines.push(`| \`${entryMode}\` | ${entry.title} | \`${command(models.get(`${family}/${entryMode}`), entryMode)}\` |`);
  }
  lines.push('', '```text', renderModelPromptGuide(guide, { audience: 'agent' }), '```');
  return lines.join('\n');
}

function imageSection(models) {
  const lines = [
    GENERATED_NOTE,
    '',
    '## Per-model rules from Sogni\'s image prompt writer',
    '',
    'Before writing an image prompt, print the rules Sogni\'s own image prompt writer uses for that model and '
      + 'operation (free and offline). They hold the per-family detail behind the table above. An edit-only or '
      + 'generation-only selector has only that operation; pass the `-m` value you will render with.',
    '',
    '| Family | Operation | Guide | Command |',
    '| --- | --- | --- | --- |',
  ];
  for (const family of IMAGE_FAMILIES) {
    for (const [mode, guide] of Object.entries(MODEL_PROMPT_GUIDES[family])) {
      lines.push(`| \`${family}\` | ${mode} | ${guide.title} | \`${command(models.get(`${family}/${mode}`), mode)}\` |`);
    }
  }
  return lines.join('\n');
}

// Replace the body of every generated section in `text`. Returns the new text
// and any problems: a missing, duplicated, unclosed or unknown section.
export function applySections(text, sections) {
  const problems = [];
  let result = text;
  const expected = new Set(sections.keys());
  for (const match of text.matchAll(/<!-- BEGIN GENERATED PROMPT GUIDE: ([^ ]+) -->/g)) {
    if (!expected.has(match[1])) problems.push(`unknown generated section "${match[1]}"`);
  }
  for (const [name, body] of sections) {
    const begin = sentinel('BEGIN', name);
    const end = sentinel('END', name);
    const start = result.indexOf(begin);
    const stop = result.indexOf(end);
    if (start < 0 || stop < 0 || stop < start) {
      problems.push(`missing or unclosed generated section "${name}"`);
      continue;
    }
    if (result.indexOf(begin, start + begin.length) >= 0) {
      problems.push(`generated section "${name}" appears twice`);
      continue;
    }
    result = `${result.slice(0, start + begin.length)}\n${body}\n\n${result.slice(stop)}`;
  }
  return { text: result, problems };
}

// The generated body of every section, per doc: [[file, Map(name -> body)]].
export async function buildPromptGuideSections() {
  const models = await commandModels();
  return [
    [VIDEO_DOC, new Map(VIDEO_FAMILIES.map((family) => [family, videoSection(family, models)]))],
    [IMAGE_DOC, new Map([[IMAGE_SECTION, imageSection(models)]])],
  ];
}

const readDocFromRepo = (file) => readFileSync(join(repoRoot, file), 'utf8');

// What each doc should contain: [{ file, current, generated, problems }].
export async function buildPromptGuideDocs({ sections, readDoc = readDocFromRepo } = {}) {
  return (sections ?? await buildPromptGuideSections()).map(([file, fileSections]) => {
    const current = readDoc(file);
    const { text, problems } = applySections(current, fileSections);
    return { file, current, generated: text, problems };
  });
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const docs = await buildPromptGuideDocs();
  const problems = docs.flatMap(({ file, problems: fileProblems }) => fileProblems.map((problem) => `${file}: ${problem}`));
  if (problems.length > 0) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  for (const { file, current, generated } of docs) {
    if (generated !== current) writeFileSync(join(repoRoot, file), generated);
    console.log(`${file}: ${generated === current ? 'unchanged' : 'updated'}`);
  }
}
